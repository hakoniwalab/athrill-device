"""Render the specification YAML files into readable Markdown under docs/spec/.

  spec/*.yaml               specification items (what the Devicetree guarantees)
  spec/models/**/*.yaml     behaviour model specifications (when present)
  spec/maps/*.yaml          per-IP maps (when present)

The YAML files are the only source; docs/spec/ is generated.

  tools/spec_doc.py           regenerate docs/spec/
  tools/spec_doc.py --check   exit 1 if docs/spec/ differs
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "spec"
NOTE = "<!-- AUTO-GENERATED by tools/spec_doc.py from {src}. Do not edit; edit the YAML. -->\n\n"


def cell(text) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def items_doc(path: Path) -> str:
    items = yaml.safe_load(path.read_text(encoding="utf-8")) or []
    area = path.stem
    lines = [NOTE.format(src=path.relative_to(ROOT).as_posix()), f"# Specification items: {area}\n"]
    lines.append("| Item | Statement | Verification | Applies to | Source |")
    lines.append("|---|---|---|---|---|")
    for it in items:
        src = it.get("source", {})
        lines.append(f"| {it['id']} | {cell(it['statement'])} | {it.get('verification', '')} | "
                     f"{it.get('applies_to', '')} | {cell(src.get('devicetree', ''))}; {cell(src.get('manual', ''))} |")
    lines.append("\n## Test specifications\n")
    lines.append("| Test spec | Stimulus | Expected |")
    lines.append("|---|---|---|")
    for it in items:
        for t in it.get("tests", []):
            lines.append(f"| {t['id']} | {cell(t['stimulus'])} | {cell(t['expect'])} |")
    return "\n".join(lines) + "\n"


def model_doc(path: Path) -> str:
    d = yaml.safe_load(path.read_text(encoding="utf-8"))
    lines = [NOTE.format(src=path.relative_to(ROOT).as_posix()),
             f"# Model specification: {d['model']} {d['version']}\n", cell(d.get("summary", "")) + "\n"]
    if d.get("fidelity_note"):
        lines.append(f"> {cell(d['fidelity_note'])}\n")
    lines.append("## Features\n")
    lines.append("| Feature | Meaning |")
    lines.append("|---|---|")
    for name, meaning in d["features"].items():
        lines.append(f"| {name} | {cell(meaning)} |")
    lines.append("\n## Terms\n")
    lines.append("| Term | Kind | Feature | Meaning |")
    lines.append("|---|---|---|---|")
    for t in d["terms"]:
        lines.append(f"| {t['name']} | {t['kind']} | {t['feature']} | {cell(t['meaning'])} |")
    lines.append("\n## Behaviour rules\n")
    lines.append("| Rule | Feature | Rule text |")
    lines.append("|---|---|---|")
    for b in d["behaviour"]:
        lines.append(f"| {b['id']} | {b['feature']} | {cell(b['rule'])} |")
    if d.get("timing"):
        lines.append(f"\n**Timing.** {cell(d['timing'])}\n")
    if d.get("out_of_scope"):
        lines.append("**Out of scope.** " + "; ".join(cell(x) for x in d["out_of_scope"]) + "\n")
    return "\n".join(lines) + "\n"


def map_doc(path: Path) -> str:
    d = yaml.safe_load(path.read_text(encoding="utf-8"))
    lines = [NOTE.format(src=path.relative_to(ROOT).as_posix()),
             f"# Map: {d['ip']} → {d['model']} {d['model_version']}\n",
             f"Compatible: {', '.join(d.get('compatible', []))}  \nManual: {cell(d.get('manual', ''))}  \n"
             f"Features: {', '.join(d.get('features', []))}\n"]
    lines.append("## Bindings\n")
    lines.append("| Term | Register | Field | Access | Note |")
    lines.append("|---|---|---|---|---|")
    for term, b in d.get("bindings", {}).items():
        field = b.get("field", "")
        if isinstance(field, list):
            field = ", ".join(field)
        reg = b.get("reg", b.get("devicetree", b.get("sequence", b.get("derived", ""))))
        lines.append(f"| {term} | {cell(reg)} | {field} | {b.get('access', '')} | {cell(b.get('note', ''))} |")
    regs = d.get("registers")
    if regs:
        lines.append(f"\n## Registers\n\nSource: {cell(d.get('registers_source', ''))}\n")
        lines.append("| Register | Offset | Reset | Fields (lsb:width) |")
        lines.append("|---|---|---|---|")
        blocks = [("", regs)] + [(f"{k}[{b['count']}] +{b['stride']}: ", b["registers"])
                                 for k, b in list(regs.items()) + [(k, d[k]) for k in ("stream",) if k in d]
                                 if isinstance(b, dict) and "registers" in b]
        for prefix, rr in blocks:
            for name, r in rr.items():
                if not (isinstance(r, dict) and "offset" in r):
                    continue
                fields = ", ".join(f"{f}({v['lsb']}:{v['width']})" for f, v in r.get("fields", {}).items())
                lines.append(f"| {prefix}{name} | {r['offset']} | {r['reset']} | {fields} |")
    return "\n".join(lines) + "\n"


def gen_map_doc(path: Path) -> str:
    d = yaml.safe_load(path.read_text(encoding="utf-8"))
    src = d["svd_source"]
    lines = [NOTE.format(src=path.relative_to(ROOT).as_posix()),
             f"# Generated map: {d['ip']} on {d['soc']} → {d['model']} {d['model_version']}\n",
             f"SVD: {src['file']} @ {src['revision'][:10]} ({src['peripheral']}); patches applied: "
             f"{', '.join(src['patches_applied']) or 'none'}  \nFeatures: {', '.join(d['features'])}\n",
             "## Bindings\n", "| Term | Register | Offset | Field | Bits | Access |", "|---|---|---|---|---|---|"]
    for term, b in d["bindings"].items():
        if "registers" not in b:
            kind = next((k for k in ("devicetree", "derived", "sequence", "not_applicable") if k in b), "unbound")
            lines.append(f"| {term} | {kind}: {cell(b[kind])} | | | | |")
            continue
        for r in b["registers"]:
            fields = r.get("fields") or [{"field": "(whole)", "lsb": 0, "width": r["size"]}]
            for f in fields:
                lines.append(f"| {term} | {r['reg']} | {r['offset']} | {f['field']} | "
                             f"{f['lsb'] + f['width'] - 1}:{f['lsb']} | {b.get('access', '')} |")
    lines.append("\n## Registers\n")
    lines.append("| Register | Offset | Reset | Fields (bound in bold) |")
    lines.append("|---|---|---|---|")
    for name, r in d["registers"].items():
        fs = ", ".join((f"**{f}**" if v["bound"] else f) + f"({v['lsb']}:{v['width']})" for f, v in r["fields"].items())
        lines.append(f"| {name} | {r['offset']} | {r['reset']} | {fs} |")
    return "\n".join(lines) + "\n"


def generate() -> dict[str, str]:
    files: dict[str, str] = {}
    index = [NOTE.format(src="spec/"), "# Specifications\n"]
    items = sorted(p for p in (ROOT / "spec").glob("*.yaml") if not p.name.startswith("svd-"))
    if items:
        index.append("## Specification items (Devicetree traceability)\n")
        for p in items:
            name = f"items-{p.stem}.md"
            files[name] = items_doc(p)
            index.append(f"- [{p.stem}]({name})")
    models = sorted((ROOT / "spec" / "models").rglob("*.yaml")) if (ROOT / "spec" / "models").exists() else []
    if models:
        index.append("\n## Behaviour model specifications\n")
        for p in models:
            name = "model-" + "-".join(p.relative_to(ROOT / "spec" / "models").with_suffix("").parts) + ".md"
            files[name] = model_doc(p)
            index.append(f"- [{p.stem}]({name})")
    maps = sorted((ROOT / "spec" / "maps").glob("*.yaml")) if (ROOT / "spec" / "maps").exists() else []
    gen_maps = sorted((ROOT / "spec" / "maps" / "gen").glob("*_gen.yaml")) if (ROOT / "spec" / "maps" / "gen").exists() else []
    if gen_maps:
        index.append("\n## Generated maps (bindings + patched ST SVD)\n")
        for p in gen_maps:
            name = f"map-{p.stem}.md"
            files[name] = gen_map_doc(p)
            index.append(f"- [{p.stem}]({name})")
    if maps:
        index.append("\n## Maps\n")
        for p in maps:
            name = f"map-{p.stem}.md"
            files[name] = map_doc(p)
            index.append(f"- [{p.stem}]({name})")
    files["README.md"] = "\n".join(index) + "\n"
    return files


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = generate()
    if args.check:
        existing = {p.name for p in OUT.glob("*.md")} if OUT.exists() else set()
        bad = sorted((existing - set(files)) |
                     {n for n, t in files.items() if not (OUT / n).exists() or (OUT / n).read_text(encoding="utf-8") != t})
        if bad:
            print("docs/spec/ is out of date; run python3 tools/spec_doc.py: " + ", ".join(bad), file=sys.stderr)
            return 1
        print(f"docs/spec/ up to date ({len(files)} files)")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.md"):
        if old.name not in files:
            old.unlink()
    for name, text in files.items():
        (OUT / name).write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} files to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
