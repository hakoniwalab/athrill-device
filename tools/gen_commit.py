"""Write the generated board tests and trace map into tests/gen/ for review.

The build still generates and compiles its own copy (tools/dt_testgen.py into
the build directory). This script runs the same generator and writes a
path-independent snapshot:

  tests/gen/test_gen_<board>.c   generated test source per board DTB
  tests/gen/trace-map.json       generated test -> test-spec ID -> node map

Absolute paths are replaced by ATHRILL_DEVICE_SOURCE_DIR / ATHRILL_TRACE_BUILD_DIR
(C string concatenation) and by repository-relative paths in the JSON.

  tools/gen_commit.py           regenerate tests/gen/
  tools/gen_commit.py --check   exit 1 if tests/gen/ differs from the generator
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / "gen"
HEADER = (
    "/* AUTO-GENERATED by tools/dt_testgen.py via tools/gen_commit.py. Do not edit.\n"
    " * Sources: spec/*.yaml (specification items) and boards/**/*.dtb (board requirement).\n"
    " * Regenerate: python3 tools/gen_commit.py   Check: python3 tools/gen_commit.py --check\n"
    " */\n"
)


def portable_c(text: str, build_dir: Path) -> str:
    def literal(prefix: str, macro: str, s: str) -> str:
        pattern = re.compile(r'"' + re.escape(prefix) + r'([^"]*)"')
        return pattern.sub(lambda m: f'{macro} "{m.group(1)}"', s)

    for root in {str(ROOT), str(ROOT.resolve())}:
        text = literal(root, "ATHRILL_DEVICE_SOURCE_DIR", text)
    for out in {str(build_dir), str(build_dir.resolve())}:
        text = literal(out, "ATHRILL_TRACE_BUILD_DIR", text)
    return HEADER + text


def portable_json(value, build_dir: Path):
    if isinstance(value, dict):
        return {k: portable_json(v, build_dir) for k, v in value.items()}
    if isinstance(value, list):
        return [portable_json(v, build_dir) for v in value]
    if isinstance(value, str):
        for out in (str(build_dir.resolve()), str(build_dir)):
            if value.startswith(out + "/") and value.endswith(".c"):
                return "tests/gen/test_gen_" + Path(value).name
            if value.startswith(out):
                return "${ATHRILL_TRACE_BUILD_DIR}" + value[len(out):]
        for root in (str(ROOT.resolve()), str(ROOT)):
            if value.startswith(root + "/"):
                return value[len(root) + 1:]
    return value


def generate() -> dict[str, str]:
    specs = sorted(p for p in (ROOT / "spec").glob("*.yaml") if not p.name.startswith("svd-"))
    dtbs = sorted((ROOT / "boards").rglob("*.dtb"))
    with tempfile.TemporaryDirectory() as tmp:
        build_dir = Path(tmp)
        cmd = [sys.executable, str(ROOT / "tools" / "dt_testgen.py")]
        for spec in specs:
            cmd += ["--spec", str(spec)]
        cmd += ["--out", str(build_dir)] + [str(d) for d in dtbs]
        subprocess.run(cmd, check=True)
        files: dict[str, str] = {}
        for source in sorted(build_dir.glob("*.c")):
            board = source.stem.removeprefix("boards__")
            files[f"test_gen_{board}.c"] = portable_c(source.read_text(encoding="utf-8"), build_dir)
        trace = json.loads((build_dir / "trace-map.json").read_text(encoding="utf-8"))
        files["trace-map.json"] = json.dumps(portable_json(trace, build_dir), indent=2, sort_keys=True) + "\n"
    return files


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = generate()
    if args.check:
        existing = {p.name for p in OUT.glob("*")} if OUT.exists() else set()
        stale = sorted(existing - set(files))
        changed = sorted(name for name, text in files.items()
                         if not (OUT / name).exists() or (OUT / name).read_text(encoding="utf-8") != text)
        if stale or changed:
            print("tests/gen/ is out of date; run python3 tools/gen_commit.py", file=sys.stderr)
            for name in changed:
                print(f"  changed: {name}", file=sys.stderr)
            for name in stale:
                print(f"  stale:   {name}", file=sys.stderr)
            return 1
        print(f"tests/gen/ up to date ({len(files)} files)")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*"):
        if old.name not in files:
            old.unlink()
    for name, text in files.items():
        (OUT / name).write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} files to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
