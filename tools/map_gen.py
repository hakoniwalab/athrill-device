"""Generate complete maps from hand-written bindings and the patched ST SVD.

  spec/bindings/<ip>.yaml        hand-written: model terms -> SVD register/field names
  ST SVD (pinned) + spec/svd-patches.yaml   canonical register definitions
      -> spec/maps/gen/<ip>__<soc>_gen.yaml   generated: bindings resolved to offsets,
                                               bit positions, widths, reset values, access;
                                               every SVD register of the peripheral listed

  tools/map_gen.py [--svd-dir build/svd]            regenerate spec/maps/gen/
  tools/map_gen.py --check [--svd-dir build/svd]    exit 1 if spec/maps/gen/ is stale

Errors stop the generation: a binding naming a register or field the SVD does not have,
an access kind the SVD contradicts, or a term of a declared feature left unbound.
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import svd_map  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
BIND = ROOT / "spec" / "bindings"
OUT = ROOT / "spec" / "maps" / "gen"
HEADER = ("# AUTO-GENERATED by tools/map_gen.py from {binding}, the pinned ST SVD ({svd}) and\n"
          "# spec/svd-patches.yaml. Do not edit; edit the binding or record an SVD patch.\n")
NON_REGISTER = ("devicetree", "derived", "sequence")
WRITE_KINDS = {"rw", "wo", "w1c", "w1s", "w0c", "rs"}
READ_KINDS = {"rw", "ro", "rc", "rs"}


def short(soc: str) -> str:
    return soc.split(",")[-1].replace("stm32", "")


def model_terms(model: str) -> dict[str, dict]:
    for path in (ROOT / "spec" / "models").rglob("*.yaml"):
        d = yaml.safe_load(path.read_text(encoding="utf-8"))
        if d.get("model") == model:
            return {t["name"]: t for t in d["terms"]}
    raise SystemExit(f"model {model}: no spec/models file")


def pattern(name: str):
    import re
    keys = re.findall(r"\{(\w+)\}", name)
    rx = re.escape(name)
    for k in keys:
        rx = rx.replace(re.escape("{" + k + "}"), f"(?P<{k}>\\d+)", 1)
    return re.compile("^" + rx + "$"), keys


def substitute(name: str, vars_: dict) -> str:
    for k, v in (vars_ or {}).items():
        name = name.replace("{" + k + "}", str(v))
    return name


def expand(name: str, table: dict, aliases: dict) -> list[tuple[str, dict]]:
    """Resolve a name, possibly with {var} placeholders, against SVD names."""
    if "{" not in name:
        real = aliases.get(name, name)
        return [(real, {})] if real in table else []
    rx, keys = pattern(name)
    out = []
    for candidate in table:
        m = rx.match(candidate)
        if m:
            out.append((candidate, {k: int(m.group(k)) for k in keys}))
    return sorted(out, key=lambda kv: tuple(kv[1].values()))


def access_conflict(kind: str, svd_access: str) -> bool:
    if kind in WRITE_KINDS and svd_access == "read-only":
        return True
    if kind in READ_KINDS and svd_access == "write-only":
        return True
    return False


def resolve(binding_path: Path, soc: str, svd: svd_map.Svd, src: dict) -> dict:
    b = yaml.safe_load(binding_path.read_text(encoding="utf-8"))
    peripheral = b["svd"][soc]
    regs = svd.registers(peripheral)
    aliases = (b.get("aliases") or {})
    errors: list[str] = []
    resolved: dict[str, dict] = {}
    for term, spec in b["bindings"].items():
        if any(k in spec for k in NON_REGISTER) or "reg" not in spec:
            resolved[term] = dict(spec)
            continue
        reg_names = spec["reg"] if isinstance(spec["reg"], list) else [spec["reg"]]
        fields = spec.get("field")
        if isinstance(fields, dict):
            if soc not in fields:
                resolved[term] = {"not_applicable": soc, **{k: v for k, v in spec.items() if k not in ("reg", "field")}}
                continue
            fields = fields.get(soc)
        out_regs = []
        other = spec.get("svd_peripheral")
        table = svd.registers(other) if other else regs
        for rn in reg_names:
            matches = expand(rn, table, aliases)
            if not matches:
                errors.append(f"{term}: register {rn} not in SVD {peripheral}")
                continue
            for svd_rn, vars_ in matches:
                reg = table[svd_rn]
                entry = {"reg": svd_rn, "offset": f"0x{reg['offset']:02X}", "size": reg["size"]}
                if other:
                    entry["peripheral"] = other
                if vars_:
                    entry["index"] = vars_
                if fields is not None:
                    flist = fields if isinstance(fields, list) else [fields]
                    fout = []
                    for fpat in flist:
                        fmatches = expand(substitute(fpat, vars_), reg["fields"], {})
                        if not fmatches:
                            if len(reg_names) > 1 or len(matches) > 1 and "{" in fpat:
                                continue
                            errors.append(f"{term}: field {svd_rn}.{substitute(fpat, vars_)} not in SVD {peripheral}")
                            continue
                        for fn, fvars in fmatches:
                            f = reg["fields"][fn]
                            if access_conflict(spec.get("access", "rw"), f["access"]):
                                errors.append(f"{term}: access {spec.get('access')} but SVD {svd_rn}.{fn} is {f['access']}")
                            item = {"field": fn, "lsb": f["lsb"], "width": f["width"], "svd_access": f["access"]}
                            if fvars:
                                item["index"] = fvars
                            fout.append(item)
                    if not fout:
                        continue
                    entry["fields"] = fout
                elif access_conflict(spec.get("access", "rw"), reg["access"]):
                    errors.append(f"{term}: access {spec.get('access')} but SVD {svd_rn} is {reg['access']}")
                out_regs.append(entry)
        if fields is not None and not out_regs and not any(e.startswith(term + ":") for e in errors):
            errors.append(f"{term}: no field {fields} in {reg_names} of SVD {peripheral}")
        resolved[term] = {k: v for k, v in spec.items() if k not in ("reg", "field", "svd_peripheral")}
        resolved[term]["registers"] = out_regs
    terms = model_terms(b["model"])
    for name, t in terms.items():
        if t["feature"] in b["features"] and name not in b["bindings"]:
            errors.append(f"term {name} (feature {t['feature']}) is not bound")
    for name in b["bindings"]:
        if name not in terms:
            errors.append(f"binding {name}: not a term of model {b['model']}")
    if errors:
        raise SystemExit(f"{binding_path.relative_to(ROOT)} [{soc}]:\n  " + "\n  ".join(errors))
    bound = {(r["reg"], f["field"]) for v in resolved.values() for r in v.get("registers", []) for f in r.get("fields", [])}
    bound |= {(r["reg"], None) for v in resolved.values() for r in v.get("registers", []) if not r.get("fields")}
    gen_regs = {}
    for rn, r in sorted(regs.items(), key=lambda kv: kv[1]["offset"]):
        gen_regs[rn] = {
            "offset": f"0x{r['offset']:02X}", "size": r["size"], "reset": f"0x{r['reset']:08X}", "access": r["access"],
            "fields": {fn: {"lsb": f["lsb"], "width": f["width"], "access": f["access"],
                            "bound": (rn, fn) in bound or (rn, None) in bound}
                       for fn, f in sorted(r["fields"].items(), key=lambda kv: kv[1]["lsb"])},
        }
    svd_info = src["svd"][soc]
    patches = [f"{p['peripheral']}.{p['register']}" for p in svd_map.load_patches(soc)
               if p["peripheral"] == peripheral or p["peripheral"] in (svd.periph[peripheral].get("derivedFrom") or "",)]
    out = {k: v for k, v in b.items() if k not in ("bindings", "svd")}
    out["soc"] = soc
    out["svd_source"] = {"file": svd_info["file"], "repository": svd_info["repository"],
                         "revision": svd_info["revision"], "peripheral": peripheral, "patches_applied": patches}
    out["bindings"] = resolved
    out["registers"] = gen_regs
    return out


def amap(data: dict, binding: str) -> str:
    """Line-oriented data file for the runtime loader (no code is generated).

    ip/model/soc/compatible/features/const lines, then
      reg  <name> <offset> <size> <reset> <stored_mask>
      term <name> <access> <reg> <field>:<lsb>:<width> [...]     register-bound term
      term <name> <kind>                                          devicetree/derived/sequence term
    stored_mask = bits of fields the SVD (patched) marks writable; other bits read as reset.
    """
    lines = [f"# AUTO-GENERATED by tools/map_gen.py from {binding} and the patched ST SVD. Do not edit.",
             f"ip {data['ip']}", f"model {data['model']} {data['model_version']}", f"soc {data['soc']}",
             "compatible " + " ".join(data["compatible"]), "features " + " ".join(data["features"])]
    for key, value in (data.get("constants") or {}).items():
        if isinstance(value, int):
            lines.append(f"const {key} {value}")
    for name, r in data["registers"].items():
        stored = 0
        for f in r["fields"].values():
            if f["access"] in ("read-write", "write-only", "writeOnce", "read-writeOnce"):
                stored |= ((1 << f["width"]) - 1) << f["lsb"]
        lines.append(f"reg {name} {r['offset']} {r['size']} {r['reset']} 0x{stored & 0xFFFFFFFF:08X}")
    for term, b in data["bindings"].items():
        if "registers" not in b:
            kind = next((k for k in ("devicetree", "derived", "sequence", "not_applicable") if k in b), "unbound")
            lines.append(f"term {term} {kind}")
            continue
        for r in b["registers"]:
            fields = " ".join(f"{f['field']}:{f['lsb']}:{f['width']}" for f in r.get("fields", []))
            lines.append(f"term {term} {b.get('access', 'rw')} {r['reg']} {fields}".rstrip())
    return "\n".join(lines) + "\n"


def generate(svd_dir: Path) -> dict[str, str]:
    src = yaml.safe_load((ROOT / "spec" / "svd-sources.yaml").read_text(encoding="utf-8"))
    cache: dict[str, svd_map.Svd] = {}
    files: dict[str, str] = {}
    for path in sorted(BIND.glob("*.yaml")):
        b = yaml.safe_load(path.read_text(encoding="utf-8"))
        for soc in b["svd"]:
            svd = cache.setdefault(soc, svd_map.Svd(svd_dir / src["svd"][soc]["file"], svd_map.load_patches(soc)))
            data = resolve(path, soc, svd, src)
            name = f"{path.stem}__{short(soc)}_gen.yaml"
            text = HEADER.format(binding=path.relative_to(ROOT).as_posix(), svd=src["svd"][soc]["file"])
            files[name] = text + yaml.safe_dump(data, sort_keys=False, width=120)
            files[name.replace("_gen.yaml", "_gen.amap")] = amap(data, path.relative_to(ROOT).as_posix())
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--svd-dir", type=Path, default=ROOT / "build" / "svd")
    args = ap.parse_args()
    files = generate(args.svd_dir)
    if args.check:
        stale = [n for n, t in files.items() if not (OUT / n).exists() or (OUT / n).read_text(encoding="utf-8") != t]
        extra = [p.name for p in OUT.glob("*_gen.*") if p.name not in files] if OUT.exists() else []
        if stale or extra:
            print("spec/maps/gen/ out of date; run python3 tools/map_gen.py: " + ", ".join(stale + extra), file=sys.stderr)
            return 1
        print(f"spec/maps/gen/ up to date ({len(files)} files)")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*_gen.*"):
        if old.name not in files:
            old.unlink()
    for n, t in files.items():
        (OUT / n).write_text(t, encoding="utf-8")
    print(f"wrote {len(files)} generated maps to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
